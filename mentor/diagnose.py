"""Assistant-authored hypothesis: suppress a student's own erroneous step token.

No reference implementation, correct next-token label, gradients or optimizer.
These probes are causal diagnostics; they cannot promote a checkpoint.
"""
import copy,hashlib,json,os,sys,time
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];HERE=ROOT/'mentor'
sys.path.insert(0,str(ROOT/'rsi100'))
os.environ.setdefault('LS_CPU_THREADS','4')
import engine as e
import torch

def token_stats(logits,token,tok):
    other=logits.clone();other[token]=-torch.inf
    values,indices=logits.topk(8)
    return {'bad_token_logit':float(logits[token]),
      'bad_token_log_odds':float(logits[token]-torch.logsumexp(other,0)),
      'top':[{'id':int(i),'piece':tok.decode([int(i)]),'logit':float(v)} for v,i in zip(values,indices)]}

@torch.inference_mode()
def capture(model,ids):
    found=[]
    handle=model.model.language_model.layers[31].mlp.down_proj.register_forward_pre_hook(
      lambda module,inputs:found.append(inputs[0][0,-1].detach().float().clone()))
    try:logits=model(input_ids=ids,use_cache=False,logits_to_keep=1).logits[0,-1].float()
    finally:handle.remove()
    assert len(found)==1,'The final physical layer must have one visit'
    return logits,found[0]

@torch.inference_mode()
def main():
    model,_=e.cr.load('baseline');tok=e.cr.tokenizer();best=e.read_checkpoint('best.pt');e.apply(model,best)
    task=next(t for t in e.DATA['search']+e.DATA['guard'] if t['id']=='overlap_count')
    prompt=e.cr.prompt(tok,task['prompt']);torch.manual_seed(0)
    generation=model.generate(input_ids=prompt,max_new_tokens=160,use_cache=True,do_sample=False,
      pad_token_id=tok.eos_token_id,return_dict_in_generate=True,output_scores=True)
    own_ids=generation.sequences[0,prompt.shape[1]:].tolist()
    own_text=tok.decode(own_ids,skip_special_tokens=True)
    report={'kind':'causal diagnostic only; no checkpoint promotion','controller':'assistant-authored hypothesis',
      'parent_checkpoint_sha256':e.cr.file_hash(e.CK/'best.pt'),'task':'overlap_count',
      'student_output':own_text,'student_token_ids':own_ids,'backward_passes':0,
      'reference_solution_or_correct_token_provided':False,'hypothesis':
      'The generated step expression uses match length and skips overlaps; test contextual suppression of its own length-call token.',
      'source_hashes':{'mentor/diagnose.py':e.cr.file_hash(Path(__file__))}}
    marker='i += len(sub)'
    if marker not in own_text:
        report.update(status='pattern_not_present; inspect actual response before choosing a new hypothesis')
        e.cr.atomic_json(HERE/'diagnostic_001.json',report);return
    bad_char=own_text.index('len',own_text.index(marker))
    boundaries=[len(tok.decode(own_ids[:i],skip_special_tokens=True)) for i in range(len(own_ids)+1)]
    def index_for(char):
        return next(i for i in range(len(own_ids)) if boundaries[i]<=char<boundaries[i+1])
    target=index_for(bad_char);bad_token=own_ids[target]
    assert 'len' in tok.decode([bad_token]),'Inspect token boundary before editing'
    # Preserve earlier length-call contexts generated by this same student.
    chars=[];pos=0
    while True:
        pos=own_text.find('len(',pos)
        if pos<0 or pos>=bad_char:break
        chars.append(pos);pos+=4
    assert chars,'No student-generated preservation context'
    indices=[target]+[index_for(c) for c in chars]
    contexts=[torch.cat([prompt,generation.sequences[:,prompt.shape[1]:prompt.shape[1]+i]],dim=1) for i in indices]
    captures=[capture(model,ids) for ids in contexts]
    h=captures[0][1];preserve=torch.stack([c[1] for c in captures[1:]])
    ridge=1e-4*float(preserve.square().sum(1).mean())
    gram=preserve@preserve.T+ridge*torch.eye(len(preserve))
    residual=h-preserve.T@torch.linalg.solve(gram,preserve@h)
    assert float(residual.norm())>1e-6
    direction=residual/residual.norm()
    output=model.get_output_embeddings().weight[bad_token].detach().float().clone()
    output=output/output.norm()
    generator=torch.Generator().manual_seed(20261104401)
    random=torch.randn(output.shape,generator=generator);random-=output*torch.dot(random,output);random/=random.norm()
    report.update(target_index=target,bad_token_id=bad_token,bad_token_piece=tok.decode([bad_token]),
      target_prefix=tok.decode(own_ids[:target]),
      generation_score=token_stats(generation.scores[target][0].float(),bad_token,tok),
      prefill_score=token_stats(captures[0][0],bad_token,tok),
      preservation_prefixes=[tok.decode(own_ids[:i]) for i in indices[1:]],
      activation_norm=float(h.norm()),residual_activation_norm=float(residual.norm()),
      preservation_projection_ratios=(preserve@direction/preserve.norm(dim=1)).tolist(),probes=[])
    torch.save({'input_direction':direction,'bad_output_direction':output,'random_output_direction':random,
      'parent_checkpoint_sha256':report['parent_checkpoint_sha256'],'bad_token_id':bad_token,
      'student_prefix_token_ids':own_ids[:target],'backward_passes':0},HERE/'directions_001.pt')
    norm=best['dense_weight'].float().norm()
    variants=[('negative',.001),('negative',.003),('negative',.01),('reverse',.003),('random',.003)]
    try:
        for kind,fraction in variants:
            vector=random if kind=='random' else output
            sign=1 if kind=='reverse' else -1
            proposal=copy.deepcopy(best)
            proposal['dense_weight']=(best['dense_weight'].float()+sign*fraction*norm*torch.outer(vector,direction)).to(best['dense_weight'].dtype)
            e.apply(model,proposal)
            scores=[token_stats(capture(model,ids)[0],bad_token,tok) for ids in contexts]
            row={'kind':kind,'requested_relative_norm':fraction,
              'actual_relative_norm':float((proposal['dense_weight'].float()-best['dense_weight'].float()).norm()/norm),
              'changed_values':int((proposal['dense_weight']!=best['dense_weight']).sum()),
              'target':scores[0],'preservation_contexts':scores[1:]}
            report['probes'].append(row);e.cr.atomic_json(HERE/'diagnostic_001.json',report)
            print('MENTOR_PROBE',json.dumps({'kind':kind,'fraction':fraction,'bad_token_log_odds':scores[0]['bad_token_log_odds'],'changed_values':row['changed_values']}),flush=True)
    finally:e.apply(model,best)
    report.update(status='diagnostic_complete; original checkpoint restored',
      directions_sha256=e.cr.file_hash(HERE/'directions_001.pt'),checkpoint_promoted=False)
    e.cr.atomic_json(HERE/'diagnostic_001.json',report)
    print('MENTOR_DIAGNOSTIC_COMPLETE',flush=True)

if __name__=='__main__':main()
